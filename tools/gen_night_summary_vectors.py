#!/usr/bin/env python3
"""Write crates/oura-analysis/src/ported/night_summary_vectors.rs: random nights of ring series
(motion, temperature, HR/HRV events) with the stage string and the results of
`score_daily_exact.night_summary` (lowest HR and its time, average RMSSD, highest temperature, time in bed).

    python tools/gen_night_summary_vectors.py [N_CASES] [SEED]
"""
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import score_daily_exact as D  # noqa: E402


def case(r):
    start_ms = (1_790_000_000 + r.randrange(0, 5000)) * 1000 + r.choice((0, 0, 400, 700))
    hours = r.choice((3.0, 6.5, 8.0, 9.2))
    end_ms = start_ms + int(hours * 3600 * 1000)
    start_s, end_s = start_ms / 1000, end_ms / 1000
    motion = [(t, r.choice((0, 0, 1, 3, 8, 30, 300)))
              for t in (start_s - 20 + 30 * k + r.random() * 25 for k in range(int((end_s - start_s) / 30) + 2))
              if r.random() < 0.7]
    base = r.randint(3100, 3500) / 100
    temp = [(t, round(base + r.gauss(0, 0.3), 2) if r.random() > 0.05 else 0.0)
            for t in (start_s - 10 + 60 * k + r.random() * 40 for k in range(int((end_s - start_s) / 60) + 2))
            if r.random() < 0.9]
    hrv = []
    t = start_s + r.randint(0, 600)
    while t < end_s + 1200:
        n = r.choice((1, 3, 5, 6))
        hrv.append((t, [r.choice((0, r.randint(45, 90))) for _ in range(n)], [r.choice((0, r.randint(15, 120))) for _ in range(n)]))
        t += n * 300 + r.randint(0, 120)
    n_rows = int((end_s - start_s) / 30) + 2
    stages = [r.choice((1, 2, 2, 2, 3, 4)) for _ in range(n_rows)] if r.random() < 0.85 else None
    return (motion, temp, hrv), start_ms, end_ms, stages


def fmt_f(x):
    return repr(float(x))


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 10
    r = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 5)
    out = ["// @generated by tools/gen_night_summary_vectors.py", "",
           "struct NightCase {", "    motion: &'static [(f64, i64)],", "    temp: &'static [(f64, f64)],",
           "    hrv: &'static [(f64, &'static [u8], &'static [u8])],", "    start_ms: i64,", "    end_ms: i64,",
           "    stages: Option<&'static [u8]>,", "    lowest_hr: u32,", "    lowest_hr_time: u32,", "    rmssd: u32,",
           "    highest_temp: u16,", "    time_in_bed: i64,", "}", "", "const NIGHT_CASES: &[NightCase] = &["]
    for _ in range(n):
        series, s, e, stages = case(r)
        lo, lot, rm, ht, tib, _motion = D.night_summary(series, s, e, stages)
        motion, temp, hrv = series
        out.append("    NightCase {")
        out.append("        motion: &[" + ", ".join(f"({fmt_f(t)}, {v})" for t, v in motion) + "],")
        out.append("        temp: &[" + ", ".join(f"({fmt_f(t)}, {fmt_f(v)})" for t, v in temp) + "],")
        out.append("        hrv: &[" + ", ".join(f"({fmt_f(t)}, &{h}, &{m})" for t, h, m in hrv) + "],")
        out.append(f"        start_ms: {s}, end_ms: {e},")
        out.append("        stages: " + ("None," if stages is None else f"Some(&{stages}),"))
        out.append(f"        lowest_hr: {lo}, lowest_hr_time: {lot}, rmssd: {rm}, highest_temp: {ht}, time_in_bed: {tib},")
        out.append("    },")
    out.append("];")
    path = HERE.parent / "crates/oura-analysis/src/ported/night_summary_vectors.rs"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {n} cases to {path}")


main()
