#!/usr/bin/env python3
"""Write crates/oura-analysis/src/ported/sleep_inputs_app_vectors.rs from the Python port: random
synthetic sleep scans with the efficiency, score and contributors that `app_sleep_score` returns.

    python tools/gen_public_vectors_sleep_app.py [N]

The seed is fixed. The script imports only `sleep_score_inputs.py`.
"""
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sleep_score_inputs as P


def write_app(n=80):
    """Random scans through `period_from_scan` / `app_sleep_score` (Python port)."""
    r = random.Random(31)
    lines = [
        "// Reference vectors from the Python port tools/sleep_score_inputs.py on random synthetic scans.",
        "// Generated by tools/gen_public_vectors_sleep_app.py; do not edit.",
        "struct AppVec {",
        "    age: u32,",
        "    start: i64,",
        "    tz: i32,",
        "    chrono: Option<(u8, i32)>,",
        "    // [time in bed, deep, light, rem, latency, wake-ups, restless, got up, midpoint]",
        "    scan: [u32; 9],",
        "    efficiency: u32,",
        "    score: u32,",
        "    contributors: [u32; 7],",
        "}",
        f"const APP_CASES: [AppVec; {n}] = [",
    ]
    for k in range(n):
        tib = r.choice([r.randint(1, 40), r.randint(200, 1000), r.randint(500, 900), 0x708])
        asleep = r.randint(0, max(tib - 1, 0)) if r.random() < 0.8 else int(tib * r.uniform(0.7, 0.95))
        asleep = min(asleep, tib)
        deep = r.randint(0, asleep)
        rem = r.randint(0, asleep - deep)
        light = asleep - deep - rem
        latency = r.choice([0, 1, r.randint(2, 60), r.randint(2, 254), 0xFF])
        mean = (r.randint(1, max(tib, 1)) if asleep else 0)
        sc = P.Scan(tib, deep, light, rem, latency, r.randint(0, 12), r.randint(0, 200), r.randint(0, 6), mean,
                    max(tib - 1, 0))
        age = r.choice([r.randint(0, 100), r.randint(18, 70)])
        age = 31 if age in (28, 29) else age
        start = r.randint(1_500_000_000, 1_900_000_000)
        tz = r.choice([0, 60, 120, -300, 330, -480, 545])
        chrono = None if k % 4 == 0 else (r.choice([0, 1, 2, 3, 4]), r.choice([r.randint(-86400, 86400), r.randint(0, 43200), 0]))
        out = P.app_sleep_score(sc, age, start, tz, chrono)
        per = P.period_from_scan(sc, start, tz)
        ch = "None" if chrono is None else f"Some(({chrono[0]}, {chrono[1]}))"
        scan = [sc.time_in_bed, sc.deep, sc.light, sc.rem, sc.latency, sc.wake_ups, sc.restless, sc.got_up, sc.midpoint]
        lines.append(f"    AppVec {{ age: {age}, start: {start}, tz: {tz}, chrono: {ch}, scan: {scan}, "
                     f"efficiency: {per.efficiency}, score: {out.score}, contributors: {list(out.contributors)} }},")
    lines.append("];")
    out_path = HERE.parent / "crates/oura-analysis/src/ported/sleep_inputs_app_vectors.rs"
    out_path.write_text("\n".join(lines) + "\n")
    print(f"{n} app cases -> {out_path}")


if __name__ == "__main__":
    write_app(int(sys.argv[1]) if len(sys.argv) > 1 else 80)
