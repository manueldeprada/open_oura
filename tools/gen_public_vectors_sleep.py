def gen_sleep_score(n=120):
    r = random.Random(SEED + 3)
    lines = ["// Reference vectors from the Python port tools/sleep_score.py on random inputs.",
             "// Generated by tools/gen_public_vectors_sleep.py; do not edit.",
             f"// (day, reference, x, result bits)\nconst TIMING: [(u8, i64, i64, u32); {n}] = ["]
    for _ in range(n):
        day = r.choice([0, 1, 2, 3, 4, 5, 6, 7, 9, 255])
        ref = r.choice([r.randint(-200, 600), r.randint(-3000, 3000), 0])
        x = r.choice([r.randint(-300, 700), r.randint(-3000, 3000), r.randint(-60, 120)])
        bits = struct.unpack("<I", struct.pack("<f", SS.timing_score(day, ref, x)))[0]
        lines.append(f"    ({day}, {ref}, {x}, {bits}),")
    lines.append("];")
    for name, kind in (("CALCULATE", "calc"), ("MINUTES", "minutes")):
        lines.append(f"// ([age, 7 stage/ratio args, ext, mid, day, ref], contributors, total)\n"
                     f"const {name}: [([i64; 12], [u32; 7], u32); {n}] = [")
        for _ in range(n):
            q = score_args(r)
            if kind == "calc":
                args = [q["tib"], q["deep"], q["light"], q["rem"], q["lat"], q["rest"], q["toss"]]
                want = SS.sleep_score(q["age"], *args, q["ext"], q["mid"], q["day"], q["ref"])
            else:
                args = [q["tib"], q["deep"], q["rem"], q["light"] & 0xFF, q["lat"], q["rest"], q["toss"]]
                want = SS.sleep_score_minutes(q["age"], *args, q["ext"], q["mid"], q["day"], q["ref"])
            row = [q["age"], *args, q["ext"], q["mid"], q["day"], q["ref"]]
            lines.append(f"    ({row}, {list(want[0])}, {want[1]}),")
        lines.append("];")
    write("sleep_score", "\n".join(lines) + "\n")


# ---- breathing rate ------------------------------------------------------------------------------

def br_night(r, epochs):
    bedtime = r.randrange(1_600_000_000_000, 1_800_000_000_000)
    base = r.uniform(45, 85)
    f = r.uniform(0.18, 0.30)
    amp = r.uniform(10, 60)
    ibi, ts, t = [], [], bedtime - 40000
    end = bedtime + 30000 * epochs
    drift = r.uniform(0, 8000)
    while t < end:
        v = 60000 / base + amp * math.sin(2 * math.pi * f * (t - bedtime) / 1000) + r.gauss(0, 12)
        v += 150 * math.sin((t - bedtime) / drift) if drift > 200 else 0
        t += max(300, int(v))
        if r.random() < 0.01:
            t += r.randint(1000, 90000)       # dropout
        x = int(max(300, v))
        if r.random() < 0.01:
            x = r.choice([2000, 2500, 4000, 65535])
        ts.append(t)
        ibi.append(min(x, 65535))
    kind = r.randrange(10)
    if kind == 0:                             # no IBIs
        ibi, ts = [], []
    elif kind == 1:                           # sparse IBIs
        keep = [i for i in range(len(ibi)) if r.random() < 0.05]
        ibi, ts = [ibi[i] for i in keep], [ts[i] for i in keep]
    elif kind == 2:                           # unsorted timestamps
        idx = list(range(len(ibi)))
        r.shuffle(idx)
        ibi, ts = [ibi[i] for i in idx], [ts[i] for i in idx]
    elif kind == 3:                           # zeros and values around the 1999 ms limit
        ibi = [r.choice([0, 1, 300, 1999, 2000]) if r.random() < 0.3 else x for x in ibi]
    mode = r.random()
    if mode < 0.4:
        motion = [0] * epochs
    elif mode < 0.8:
        motion = [r.choice([0, 0, 0, 0, 1, 2, 5, 40]) for _ in range(epochs)]
    else:
        motion = [r.randrange(256) for _ in range(epochs)]
    return bedtime, ibi, ts, motion


def records_hash(recs):
    h = None
    for rec in recs:
        data = rec[0].to_bytes(8, "little", signed=False) + bytes(rec[1:6])
        h = fnv(data) if h is None else fnv(data, h)
    return h


def gen_breathing_rate():
    out = []

    def case(bed, ibi, ts, motion, first):
        recs = [tuple(x) for x in BR.epoch_records(bed, ibi, ts, motion)]
        avg = tuple(BR.breathing_rate(bed, ibi, ts, motion))
        deltas, prev = [], bed
        for t in ts:
            deltas.append(t - prev)
            prev = t
        firstrecs = ", ".join("[" + nums(x[1:6]) + "]" for x in recs[:first])
        h = records_hash(recs) if recs else 0xCBF29CE484222325
        return (f"    Vector {{ bedtime_ms: {bed}, ibi: &[{nums(ibi)}], ts_delta: &[{nums(deltas)}], "
                f"motion: &[{nums(motion)}], n_records: {len(recs)}, records_hash: 0x{h:016x}, "
                f"first_records: &[{firstrecs}], averages: ({avg[0]!r}, {avg[1]!r}, {avg[2]!r}) }},"), avg

    r = random.Random(SEED + 5)
    kinds = {}
    while len(out) < 6:
        epochs = r.randint(20, 30)
        bed, ibi, ts, motion = br_night(r, epochs)
        kind = ("none" if not ibi else "sparse" if len(ibi) < 5 * epochs else
                "unsorted" if any(ts[k] > ts[k + 1] for k in range(len(ts) - 1)) else
                "boundary" if any(x in (0, 1, 1999, 2000) for x in ibi) else "dense")
        if kinds.get(kind, 0) >= 2 or (kind == "none" and kinds.get(kind, 0) >= 1):
            continue
        kinds[kind] = kinds.get(kind, 0) + 1
        out.append(case(bed, ibi, ts, motion, 10 ** 6)[0])
    # nights of 361 epochs: the dense one with the fewest beats, then a sparse one; both need a valid average
    best = None
    for seed in range(40):
        rr = random.Random(100 + seed)
        bed, ibi, ts, motion = br_night(rr, 361)
        if len(ibi) > 5 * 361 and (best is None or len(ibi) < len(best[1])):
            if tuple(BR.breathing_rate(bed, ibi, ts, motion)) != (0.0, 0.0, 0.0):
                best = (bed, ibi, ts, motion)
    out.append(case(*best, 3)[0])
    for seed in range(200, 400):
        rr = random.Random(seed)
        bed, ibi, ts, motion = br_night(rr, 361)
        if 0 < len(ibi) < 5 * 361 and ts == sorted(ts) and tuple(BR.breathing_rate(bed, ibi, ts, motion)) != (0.0, 0.0, 0.0):
            out.append(case(bed, ibi, ts, motion, 3)[0])
            break
    head = ("// Reference vectors from the Python port tools/breathing_rate.py on synthetic nights.\n"
            "// Generated by tools/gen_public_vectors_sleep.py; do not edit.\n"
            "/// One synthetic night and the reference output for it.\n"
            "struct Vector {\n    bedtime_ms: i64,\n    ibi: &'static [u16],\n    ts_delta: &'static [i32],\n"
            "    motion: &'static [u8],\n    n_records: usize,\n    records_hash: u64,\n"
            "    first_records: &'static [[u8; 5]],\n    averages: (f32, f32, f32),\n}\n\n"
            f"const VECTORS: [Vector; {len(out)}] = [\n")
    write("breathing_rate", head + "\n".join(out) + "\n];\n")


