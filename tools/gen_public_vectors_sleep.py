# ---- sleep regularity ------------------------------------------------------------------------------

def gen_sri(n=24):
    r = random.Random(SEED + 2)
    t0 = 1_790_000_000 // 86400 * 86400
    seqs = []
    while len(seqs) < n:
        p = SRI.SriState()
        day, ops = r.randint(0, 3), []
        for _ in range(r.randint(8, 24)):
            day += r.choice([0, 1, 1, 1, 2, 3, 20, -1])
            tz = r.choice([0, 120, -300, 60, 330])
            base = t0 + day * 86400
            start = base + r.randint(0, 86399) - 3600 * r.choice([0, 0, 6])
            end = start + r.choice([r.randint(60, 600), r.randint(600, 40000)])
            p.update_history((base, 0), (start, tz), (end, tz))
            ops.append(((base, 0), (start, tz), (end, tz)))
        want = RS.sri_calculate(p.rows(), True) & 0x1FF
        if want or len(seqs) % 8 == 7:  # keep a few sequences with no valid index
            seqs.append((ops, want))
    lines = ["// Reference vectors from the Python port tools/sri.py on random sleep sequences.",
             "// Generated by tools/gen_public_vectors_sleep.py; do not edit.", "#[allow(clippy::type_complexity)]",
             "fn sri_sequences() -> Vec<(Vec<(Time, Time, Time)>, u32)> {", "    vec!["]
    for ops, want in seqs:
        body = ", ".join(f"(({d[0]}, {d[1]}), ({s[0]}, {s[1]}), ({x[0]}, {x[1]}))" for d, s, x in ops)
        lines.append(f"        (vec![{body}], {want}),")
    lines += ["    ]", "}"]
    write("sri", "\n".join(lines) + "\n")


