def bedtime_case(r):
    kind = r.choice(("night", "night", "multi", "noise", "short"))
    n_bins = {"night": r.randint(600, 1400), "multi": r.randint(1500, 2400), "noise": r.randint(20, 1500),
              "short": r.randint(1, 200)}[kind]
    t_start = T0 + r.randint(0, 40) * 30_000 + r.choice((0, 0, 7000, 29000))
    motion = []
    if kind == "noise":
        pool = [0, 0, 1, 2, 5, 10, 20, 30, 31, 200, 255, 127, 128, 100]
        motion = [r.choice(pool) for _ in range(n_bins)]
    else:
        pos = 0
        while pos < n_bins:
            seg = r.choice(("awake", "asleep", "asleep", "asleep", "charge", "off", "restless"))
            ln = r.randint(5, 400) if seg != "asleep" else r.randint(60, 1100)
            for _ in range(min(ln, n_bins - pos)):
                if seg == "awake":
                    v = r.choice((0, 0, 3, 8, 15, 22, 30)) if r.random() < 0.7 else 0
                elif seg == "asleep":
                    v = 0 if r.random() > 0.04 else r.randint(1, 4)
                elif seg == "restless":
                    v = r.randint(0, 12) if r.random() < 0.3 else 0
                elif seg == "charge":
                    v = 255
                else:
                    v = 31
                motion.append(v)
            pos += ln
        motion = motion[:n_bins]
    ts = [t_start + 30_000 * i + (r.randint(-1500, 1500) if r.random() < 0.05 else 0) for i in range(len(motion))]
    n_t = max(1, len(motion) // 2 + r.choice((0, 0, 0, -3, 5, 50)))
    base = r.choice((3300, 3400, 3500, 3600))
    temp, warm = [], False
    for i in range(n_t):
        if r.random() < 0.01:
            warm = not warm
        v = base + (130 if warm else 0) + r.randint(-60, 60)
        temp.append(0 if r.random() < 0.08 else max(0, v))
    for _ in range(r.choice((0, 0, 1, 3))):
        a = r.randint(0, n_t)
        for i in range(a, min(n_t, a + r.randint(5, 400))):
            temp[i] = 0
    if kind == "noise":
        temp = [r.choice((0, 3200, 3400, 3500, 3600, 65535, 1)) for _ in range(n_t)]
    temp_ts = [t_start + 60_000 * i for i in range(n_t)]
    if r.random() < 0.3:
        temp_ts = [t + r.randint(-5000, 5000) for t in temp_ts]
    span = ts[-1] - ts[0]
    hr = []
    for _ in range(r.randint(1, 4)):
        a = ts[0] + r.randint(0, max(1, span))
        hr.append((a, a + r.randint(60_000, 6 * 3_600_000)))
    if r.random() < 0.1:
        hr.append((ts[-1], ts[0]))
    prev = []
    if r.random() < 0.3:
        for _ in range(r.randint(1, 3)):
            a = ts[0] + r.randint(-3 * 3_600_000, max(1, span))
            prev.append((a, a + r.randint(600_000, 8 * 3_600_000), r.randint(0, 1)))
    return dict(motion=motion, motion_ts=ts, temp=temp, temp_ts=temp_ts, hr_periods=hr, previous=prev,
                report_naps=r.random() < 0.7)


def deltas(xs):
    prev = xs[0]
    out = []
    for x in xs:
        out.append(x - prev)
        prev = x
    return out


def pairs(rl, fmt):
    return "&[" + ", ".join(fmt.format(*p) for p in rl) + "]"


def rle_pairs(xs):
    out = []
    for x in xs:
        if out and out[-1][0] == x:
            out[-1][1] += 1
        else:
            out.append([x, 1])
    return out


def detect(c):
    rc, res = BF.detect_bedtime(c["motion"], c["motion_ts"], c["temp"], c["temp_ts"], c["hr_periods"], 3500,
                                c["previous"], c["report_naps"])
    return [] if rc else [(s, e, m) for s, e, m in res]


def bedtime_state(c):
    """The module state after `detect_bedtime`, as `find` leaves it."""
    rc, M, T = BF.normalize([m & 0xFF for m in c["motion"]], list(c["motion_ts"]), c["temp"], c["temp_ts"])
    if rc or not M:
        return None
    so = []
    BF.find(M, T, c["temp"], c["hr_periods"], c["previous"], 1 if c["report_naps"] else 0, so)
    return so[0]


def gen_bedtime(n=10):
    r = random.Random(SEED + 7)
    cases, want_empty, tries = [], 2, 0
    while len(cases) < n and tries < 5000:
        tries += 1
        c = bedtime_case(r)
        if len(c["motion"]) > 1200 or len(c["motion"]) < 40:
            continue
        out = detect(c)
        if not out:
            if want_empty == 0:
                continue
            want_empty -= 1
        cases.append((c, out))
    body = ""
    for c, out in cases:
        ts, tts = c["motion_ts"], c["temp_ts"]
        body += ("    Vector {\n"
                 f"        ts0: {ts[0]},\n"
                 f"        ts_delta: {pairs(rle_pairs(deltas(ts)), '({}, {})')},\n"
                 f"        motion: {pairs(rle_pairs(c['motion']), '({}, {})')},\n"
                 f"        temp_ts0: {tts[0]},\n"
                 f"        temp_ts_delta: {pairs(rle_pairs(deltas(tts)), '({}, {})')},\n"
                 f"        temp: {pairs(rle_pairs(c['temp']), '({}, {})')},\n"
                 f"        hr: &[{', '.join(f'({s}, {e})' for s, e in c['hr_periods'])}],\n"
                 f"        previous: &[{', '.join(f'({s}, {e}, {bool(m)})'.lower() for s, e, m in c['previous'])}],\n"
                 f"        naps: {rust_bool(c['report_naps'])},\n"
                 f"        out: &[{', '.join(f'({s}, {e}, {bool(m)})'.lower() for s, e, m in out)}],\n"
                 "    },\n")
    clears = []
    for i, (c, _) in enumerate(cases):
        if len(clears) >= 10:
            break
        st = bedtime_state(c)
        if st is None:
            continue
        marks = [x for e in st.cand for x in (e.f0, e.f8) if x]
        if not marks:
            continue
        for _ in range(2):
            a = max(1, r.choice(marks) + r.randint(-3_000_000, 3_000_000))
            b = max(a + r.randint(-1000, 20_000_000), 0)
            st = bedtime_state(c)
            BF.clear_minor_periods_ms(st, a, b)
            raw = BF.state_bytes(st)
            nc = struct.unpack_from("<I", raw, 0x28)[0]
            cand = [struct.unpack_from("<QQ", raw, 0x40 + 32 * k) for k in range(5)]
            clears.append(f"    ClearCase {{ vector: {i}, a: {a}, b: {b}, n_cand: {nc}, "
                          f"cand: [{', '.join(f'({x}, {y})' for x, y in cand)}] }},\n")
    merges = []
    for k in (1, 1, 2, 3, 3, 5, 6, 8, 12, 17, 17, 4, 2, 9):
        ps = []
        for _ in range(k):
            s = r.randint(0, 40) * 100 + r.choice((0, 0, 7))
            ps.append((s, r.randint(-720, 720), s + r.choice((-5, 0, 50, 300, 900)), r.randint(-720, 720)))
        cap = r.choice((1, 4, 100))
        want = BF.merge_periods(ps, cap)
        fmt = lambda xs: "&[" + ", ".join(f"({a}, {b}, {c}, {d})" for a, b, c, d in xs) + "]"
        merges.append(f"    MergeCase {{ input: {fmt(ps)}, cap: {cap}, out: {fmt(want)} }},\n")
    head = """// Reference vectors from the Python port tools/bedtime_find.py on synthetic nights.
// Generated by tools/gen_public_vectors_sleep.py; do not edit.
/// One input of `detect_bedtime` and the reference output for it. Sequences are run-length
/// encoded as (value, count); timestamps are deltas from the previous one (the first is 0).
struct Vector {
    ts0: u64,
    ts_delta: &'static [(i32, u32)],
    motion: &'static [(u8, u32)],
    temp_ts0: u64,
    temp_ts_delta: &'static [(i32, u32)],
    temp: &'static [(u16, u32)],
    hr: &'static [(u64, u64)],
    previous: &'static [(u64, u64, bool)],
    naps: bool,
    out: &'static [(u64, u64, bool)],
}

"""
    extra = """/// `clear_minor_periods_ms(a, b)` after `detect_bedtime` on VECTORS[vector]: the candidate count
/// and the (start, end) of the five candidate entries afterwards.
struct ClearCase {
    vector: usize,
    a: u64,
    b: u64,
    n_cand: u32,
    cand: [(u64, u64); 5],
}

/// `merge_periods(input, cap)` and the reference output; records are (start, start_tz, end, end_tz).
struct MergeCase {
    input: &'static [(i64, i64, i64, i64)],
    cap: usize,
    out: &'static [(i64, i64, i64, i64)],
}

"""
    write("bedtime", head + f"const VECTORS: [Vector; {len(cases)}] = [\n" + body + "];\n\n" + extra
          + f"const CLEAR: [ClearCase; {len(clears)}] = [\n" + "".join(clears) + "];\n\n"
          + f"const MERGE: [MergeCase; {len(merges)}] = [\n" + "".join(merges) + "];\n")
    print("bedtime: vectors with output:", sum(1 for _, o in cases if o), "of", len(cases))


