def wire_phases(phases):
    packed = bytearray()
    for i in range(0, len(phases), 2):
        a, b = phases[i], phases[i + 1] if i + 1 < len(phases) else 0
        packed.append(0 if (a < 0 or b < 0 or a > 4 or b > 4) else (b << 4) | a)
    return SI.unpack_phases(bytes(packed))


def summary_night(rnd):
    start = rnd.randint(1_700_000_000, 1_900_000_000) * 1000 + rnd.choice([0, 300, 700, 999])
    nep = rnd.choice([rnd.randint(40, 200), rnd.randint(300, 700), rnd.randint(700, 1000)])
    end = start + nep * 30000 + rnd.randint(0, 29999)
    stages = []
    while len(stages) < nep:
        cur = rnd.choice([1, 1, 2, 2, 2, 3, 3, 4])
        stages += [cur] * rnd.choice([1, 2, 5, 10, 20, 40])
    stages = stages[:nep]
    if rnd.random() < 0.1:
        stages[rnd.randrange(nep)] = 0
    nslot = -(-(end - start) // 300000)
    first = start if rnd.random() < 0.4 else start + rnd.randint(0, 299999)
    base = rnd.randint(45, 70)
    hrhrv = []
    for _ in range(nslot):
        if rnd.random() < 0.15:
            hrhrv.append((0, 0))
        else:
            hrhrv.append((max(0, base + rnd.randint(-8, 12)), rnd.choice([0, rnd.randint(15, 140), rnd.randint(15, 140)])))
    nt = -(-(end - start) // 60000)
    t0 = rnd.randint(3300, 3700)
    temps, t = [], t0
    for _ in range(nt):
        t += rnd.randint(-25, 25)
        temps.append(0 if rnd.random() < rnd.choice([0.0, 0.05, 0.3]) else max(0, t))
    return dict(start_ms=start, end_ms=end, phases=stages, temps=temps, hrhrv=hrhrv,
                phases_first_ms=start, hrhrv_first_ms=first)


def gen_sleep_summary():
    r = random.Random(SEED + 11)
    lines = ["// Reference vectors from the Python port tools/sleep_summary.py on random nights.",
             "// Generated by tools/gen_public_vectors_sleep.py; do not edit.", "#[allow(clippy::type_complexity)]",
             "fn rmssd_cases() -> Vec<(Vec<u8>, Vec<u8>, i32, (u32, u32, u32))> {", "    vec!["]
    for _ in range(60):
        nsl = r.randint(1, 40)
        nep = r.choice([nsl * 10, nsl * 10 - r.randint(0, 9), nsl * 10 + r.randint(0, 15)])
        st = []
        while len(st) < nep:
            st += [r.choice([1, 2, 2, 3, 3, 4, 1])] * r.choice([1, 3, 7, 15, 30])
        st = st[:nep]
        if r.random() < 0.15:
            st[r.randrange(nep)] = 0
        rm = [r.choice([0, r.randint(10, 140)]) for _ in range(nsl)]
        off = r.choice([0, 0, r.randint(-150, 149), r.randint(-400, 400)])
        want = SM.calculate_average_rmssd(st, rm, nsl, off)
        lines.append(f"        (vec!{st}, vec!{rm}, {off}, {tuple(want)}),")
    lines += ["    ]", "}", "", "fn temperature_cases() -> Vec<(Vec<u16>, u16)> {", "    vec!["]
    for _ in range(60):
        n = r.choice([10, 29, 30, 31, 100, 150, 200, 400])
        t, temps = r.randint(3300, 3700), []
        gap = r.choice([0.0, 0.05, 0.3])
        step = r.choice([5, 25, 80])
        for _ in range(n):
            t += r.randint(-step, step)
            temps.append(0 if r.random() < gap else max(0, t))
        lines.append(f"        (vec!{temps}, {SM.nightly_temperature(temps)}),")
    lines += ["    ]", "}", "", "struct NightCase {", "    phases: Vec<u8>,", "    phases_first_ms: i64,",
              "    start_ms: i64,", "    end_ms: i64,", "    hrhrv: Vec<(u8, u8)>,", "    hrhrv_first_ms: i64,",
              "    temps: Vec<u16>,", "    rmssd: (u32, u32, u32),", "    hr8: u32,", "    temp: u16,", "}", "",
              "fn night_cases() -> Vec<NightCase> {", "    vec!["]
    rnd = random.Random(SEED + 12)
    count = 0
    while count < 8:
        n = summary_night(rnd)
        if len(n["temps"]) > 250:
            continue
        ph = wire_phases(n["phases"])
        hr = [p[0] for p in n["hrhrv"]]
        rm = [p[1] for p in n["hrhrv"]]
        off = SM.slot_offset(n["hrhrv_first_ms"], len(hr), n["start_ms"] // 1000)
        rmssd = SM.calculate_average_rmssd(SM.stage_rows(ph, n["phases_first_ms"], n["start_ms"], n["end_ms"]),
                                           rm, len(hr), off)
        lines.append(f"        NightCase {{ phases: vec!{ph}, phases_first_ms: {n['phases_first_ms']}, "
                     f"start_ms: {n['start_ms']}, end_ms: {n['end_ms']}, hrhrv: vec!{[tuple(p) for p in n['hrhrv']]}, "
                     f"hrhrv_first_ms: {n['hrhrv_first_ms']}, temps: vec!{n['temps']}, "
                     f"rmssd: ({rmssd[0]}, {rmssd[1]}, {rmssd[2]}), hr8: {SM.hr_average_times8(hr)}, "
                     f"temp: {SM.nightly_temperature(n['temps'])} }},")
        count += 1
    lines += ["    ]", "}"]
    write("sleep_summary", "\n".join(lines) + "\n")


