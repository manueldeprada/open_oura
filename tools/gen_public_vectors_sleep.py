MAX_BEATS, FIRST = 200, 12


def ibi_sequence(r, n=None):
    n = n or r.randint(150, 400)
    t = r.choice([1_700_000_000_000 + r.randrange(10 ** 9), r.randrange(1, 99_999_999_999),
                  r.randrange(10 ** 11, 2 * 10 ** 12), 0])
    hr = r.uniform(40, 110)
    kind = r.choice(["clean", "ectopic", "gaps", "bad", "noisy", "mixed", "mixed"])
    out = []
    while len(out) < n:
        base = 60000 / hr
        v = int(base + r.gauss(0, base * r.choice([0.01, 0.03, 0.08])))
        hr = min(170, max(30, hr + r.gauss(0, 0.6)))
        gap_n = 0
        if kind in ("ectopic", "mixed") and r.random() < 0.04:
            v = int(base * r.uniform(0.4, 0.7))
            out.append(v)
            v = int(base * r.uniform(1.3, 1.7))
        if kind in ("gaps", "mixed") and r.random() < 0.03:
            gap_n = r.randint(1, 8)
        if kind in ("bad", "mixed") and r.random() < 0.01:
            if r.random() < 0.4:                    # long run of implausible beats
                out += [r.choice([r.randint(100, 350), r.randint(2200, 6000)]) for _ in range(r.randint(55, 140))]
            else:
                out += [r.choice([r.randint(100, 5000), r.randint(250, 3000)]) for _ in range(r.randint(5, 90))]
        if kind in ("bad", "noisy", "mixed") and r.random() < 0.05:
            v = r.choice([0, 1, 100, 250, 2500, 4000, 65535, r.randint(0, 65535)])
        out.append(max(0, v))
        if gap_n:
            out.append(int(base * (gap_n + 1)))
    out = out[:n]
    seq = []
    for v in out:
        t += max(v, 0) if r.random() < 0.97 else r.randint(0, 3000)
        seq.append((t, v, r.choice([0, r.randint(0, 65535), r.randint(100, 900)]),
                    r.choice([0, 0, 0, 0, 3, 7, 200])))
    if r.random() < 0.25:                           # a stretch of beats with a bad input validity byte
        a = r.randrange(len(seq))
        seq = [(t, v, m, 200 if a <= k < a + r.choice([30, 65, 100]) else vin)
               for k, (t, v, m, vin) in enumerate(seq)]
    return seq


def ibi_params(r):
    if r.random() < 0.4:
        return dict(max_out=4, gap_ms=5000, flag_a=0, flag_b=1, max_bpm=150.0)
    return dict(max_out=r.choice([1, 2, 4, 4, 8]), gap_ms=r.choice([0, 1000, 5000, 5000, 9000]),
                flag_a=r.randrange(2), flag_b=r.randrange(2), max_bpm=r.choice([150.0, 150.0, 120.0, 200.0]))


class Probe(IC.IbiCorrection):
    """Records which correction paths a run reaches."""
    seen = set()

    def _median_error(self):
        before = self.D[3]
        super()._median_error()
        if before == 1 and self.D[3] == 2:
            Probe.seen.add("demote")


def _wrap(name, tag):
    orig = getattr(IC.IbiCorrection, name)

    def f(self, *a, **k):
        Probe.seen.add(tag)
        return orig(self, *a, **k)
    setattr(Probe, name, f)


for _n, _t in (("_interpolate", "interp"), ("_amp_check", "amp"), ("_too_long", "toolong"),
               ("_flush", "flush"), ("_flush_pending_rejects", "flush_pending_rejects")):
    _wrap(_n, _t)


def run_python(seq, p):
    Probe.seen = set()
    c = Probe(**p)
    out = []
    for ts, ibi, amp, vin in seq:
        out += c.feed(ts, ibi, amp, vin)
    feats = set(Probe.seen)
    if c.ts_epoch == 0 and "interp" in feats:
        feats.add("interp_small_ts")
    return out, feats


def events_hash(ev):
    h = None
    for ts, ibi, amp, val in ev:
        data = ts.to_bytes(8, "little") + ibi.to_bytes(2, "little") + amp.to_bytes(2, "little") + bytes([val])
        h = fnv(data) if h is None else fnv(data, h)
    return h if h is not None else 0xCBF29CE484222325


def rs_vector(seq, p, ev):
    beats = ", ".join(f"({t}, {i}, {a}, {v})" for t, i, a, v in seq)
    first = ", ".join(f"({t}, {i}, {a}, {v})" for t, i, a, v in ev[:FIRST])
    return (f"Vector {{ params: ({p['max_out']}, {p['gap_ms']}, {rust_bool(p['flag_a'])}, "
            f"{rust_bool(p['flag_b'])}, {p['max_bpm']!r}), beats: &[{beats}], n_events: {len(ev)}, "
            f"events_hash: 0x{events_hash(ev):016x}, first_events: &[{first}] }}")


def gen_ibi_correction():
    want_feats = ["interp", "interp_small_ts", "amp", "toolong", "flush", "demote", "flush_pending_rejects"]
    chosen, covered, combos = [], set(), set()
    default = dict(max_out=4, gap_ms=5000, flag_a=0, flag_b=1, max_bpm=150.0)
    seed = 0
    while len(chosen) < 7 and seed < 4000:  # chosen for the features they add; the first two use default parameters
        seed += 1
        r = random.Random(seed)
        seq = ibi_sequence(r)[:MAX_BEATS]
        first = len(chosen) < 2
        p = dict(default) if first else ibi_params(r)
        if first:
            seq = [(t, i, a, 0) for t, i, a, _ in ibi_sequence(r)[:MAX_BEATS]]
        out, feats = run_python(seq, p)
        new = (feats & set(want_feats)) - covered
        if first:
            if "interp" not in feats or not any(e[3] == 2 for e in out):
                continue
        elif not new and (p["flag_a"], p["flag_b"]) in combos:
            continue
        covered |= feats
        combos.add((p["flag_a"], p["flag_b"]))
        chosen.append((seq, p, out))
    print("ibi_correction: paths not reached:", sorted(set(want_feats) - covered) or "none")
    stateless = []
    for seed in range(7000, 7060):
        if len(stateless) == 2:
            break
        r = random.Random(seed)
        seq = [(t, i, a, 0) for t, i, a, _ in ibi_sequence(r, r.randint(120, 160))]
        ts = [x[0] for x in seq]
        lo, hi = ts[0], ts[-1]

        def lst():
            m = r.randint(2, 5)
            tt = sorted(r.randint(lo, hi) for _ in range(m))
            return tt, [r.choice([0, 1, 2, 5, 6, 6, 5, 7]) for _ in range(m)]
        sc, wear = lst(), lst()
        merged_ts, merged_st = IC.merge_data(sc[0], sc[1], wear[0], wear[1])
        resets = IC.next_reset_timestamp(0, merged_ts, merged_st)
        if resets == IC.M64 or resets >= hi:
            continue
        got = IC.correct_stateless(ts, [x[1] for x in seq], [x[2] for x in seq], sc[0], sc[1], wear[0], wear[1])
        stateless.append((seq, default, got, sc, wear))
    head = ("// Reference vectors from the Python port tools/ibi_correction.py on synthetic beat sequences.\n"
            "// Generated by tools/gen_public_vectors_sleep.py; do not edit.\n"
            "/// A beat sequence `(timestamp, ibi, amplitude, input validity)` and the events the reference emits.\n"
            "struct Vector {\n    params: (u16, u16, bool, bool, f32),\n"
            "    beats: &'static [(u64, u16, u16, u8)],\n    n_events: usize,\n    events_hash: u64,\n"
            "    first_events: &'static [(u64, u16, u16, u8)],\n}\n\n"
            "/// A stateless run with state-change and wear lists (default parameters).\n"
            "struct StatelessVector {\n    vector: Vector,\n    state_change_ts: &'static [u64],\n"
            "    state_change_states: &'static [u8],\n    wear_ts: &'static [u64],\n"
            "    wear_states: &'static [u8],\n}\n\n")
    body = f"const VECTORS: [Vector; {len(chosen)}] = [\n"
    body += "".join(f"    {rs_vector(s, p, o)},\n" for s, p, o in chosen) + "];\n\n"
    body += f"const STATELESS_VECTORS: [StatelessVector; {len(stateless)}] = [\n"
    for s, p, o, sc, wear in stateless:
        body += (f"    StatelessVector {{ vector: {rs_vector(s, p, o)}, state_change_ts: &[{nums(sc[0])}], "
                 f"state_change_states: &[{nums(sc[1])}], wear_ts: &[{nums(wear[0])}], "
                 f"wear_states: &[{nums(wear[1])}] }},\n")
    body += "];\n"
    write("ibi_correction", head + body)


