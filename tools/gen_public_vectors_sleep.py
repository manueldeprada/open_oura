def sleep_night(r):
    start = r.randint(1_500_000_000, 1_900_000_000) + r.choice([0, r.randint(0, 29)])
    kind = r.random()
    if kind < 0.15:
        nep = r.randint(1, 14)
    elif kind < 0.9:
        nep = r.randint(300, 900)
    else:
        nep = r.randint(900, 1300)
    end = start + nep * 30 + r.randint(0, 29)
    stages = [4] * r.choice([0, 0, 0, 3, 9, 12, 40, 150, 270, 400])
    cur = r.choice([4, 4, 2])
    while len(stages) < nep + r.choice([0, 0, 5, -3]):
        run = r.choice([1, 2, 3, 6, 15, 40, 90])
        cur = 4 if cur != 4 and r.random() < 0.35 else r.choice([1, 2, 2, 3])
        stages += [cur] * run
        if r.random() < 0.01:
            stages.append(0)
    packed = bytearray()
    for i in range(0, len(stages) - 1, 2):
        packed.append(stages[i] | (stages[i + 1] << 4))
    if len(stages) % 2:
        packed.append(stages[-1])
    if r.random() < 0.05 and len(packed) > 4:
        packed[r.randrange(len(packed))] = r.choice([0x00, 0x03, 0x05, 0x5F, 0xF4, 0x90])
    phase_shift = r.choice([0, 0, 0, 30, -30, 60, 7, -45, 300, -600])
    phase_ms = (start - start % 30 + phase_shift) * 1000 + r.choice([0, 0, 0, 400, 999, -250])
    mcount = max(0, nep + r.choice([0, 0, 5, -10, 100, -nep]))
    quiet = r.choice([0.6, 0.85, 0.97])
    motion = bytearray()
    for _ in range(mcount):
        if r.random() < quiet:
            motion.append(0 if r.random() < 0.8 else r.randint(1, 8))
        else:
            motion.append(r.choice([r.randint(9, 60), r.randint(24, 255), 255, 30, 80]))
    motion_shift = r.choice([0, 0, 0, 30, -30, 90, -120, 3600, -3600])
    motion_ms = (start - start % 30 + motion_shift) * 1000 + r.choice([0, 0, 500])
    if r.random() < 0.15:
        motion = bytearray()
    return dict(start=start, end=end, tz=r.choice([0, 60, -300, 330, 120, -420, 540, -60]),
                age=r.choice([18, 25, 30, 31, 45, 60, 80, r.randint(1, 100)]),
                phases=bytes(packed), phase_ms=phase_ms, motion=bytes(motion), motion_ms=motion_ms,
                chrono=r.choice([None, (r.randint(0, 6), r.randint(-3600, 20 * 3600)), (255, r.randint(0, 40000))]))


