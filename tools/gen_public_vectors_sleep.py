# ---- lowest heart rate -----------------------------------------------------------------------------

def hr_series(r):
    n = r.choice((1, 3, 6, 7, 8, 12, 30, 60, 100, 140))
    mode, base, arr = r.randrange(5), r.randint(40, 75), []
    for k in range(n):
        if mode == 0:
            v = r.randint(35, 120)
        elif mode == 1:
            v = max(1, int(base + 20 * max(0.0, 1 - k / 25) + r.gauss(0, 2)))
        elif mode == 2:
            v = base + r.choice((0, 0, 1, 2, 5, 30, 90))
        elif mode == 3:
            v = int(base + 15 * (1 - k / max(n, 1)) + r.gauss(0, 1.5))
        else:
            v = r.randint(40, 200)
        arr.append(0 if r.random() < 0.08 else min(255, max(0, v)))
    return arr


def gen_lowest_hr(n=150):
    r = random.Random(SEED + 1)
