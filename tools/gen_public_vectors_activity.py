# ---- actinfo: one day of per-minute MET bytes through add_activity and statistics ----------------

def rand_day(r, n):
    """n per-minute MET*10 bytes in stretches (sleep, desk, walk, workout, idle, non-wear, noise);
    each value repeats for 3 to 15 minutes."""
    out = []
    while len(out) < n:
        kind = r.choices(["sleep", "desk", "walk", "work", "idle", "nonwear", "noise"], [3, 4, 3, 2, 3, 1, 2])[0]
        ln = r.randint(1, 240 if kind in ("sleep", "desk", "nonwear") else 90)
        lo, hi = {"sleep": (5, 10), "desk": (9, 17), "walk": (18, 45), "work": (45, 140), "idle": (0, 14),
                  "nonwear": (1, 1), "noise": (0, 255)}[kind]
        while ln > 0:
            v = r.randint(lo, hi)
            if kind == "noise" and v == 1:
                v = 2
            rep = min(ln, r.randint(3, 15))
            out += [v] * rep
            ln -= rep
    return out[:n]


def rand_case(r):
    n = r.choice([1440, 1440, 1440, r.randint(10, 1439)])
    return dict(
        met=rand_day(r, n), age=r.choice([r.randint(13, 90), r.randint(18, 60)]),
        gender=r.choice([1, 1, 2, 2, 3, 0]), weight_kg=r.randint(40, 130), bmr=r.randint(1100, 2600),
        target_mult=r.choice([100, 100, 50, 150, 200, 25, 24, 201, 0, r.randint(0, 255)]),
        target_type=r.choice([0, 0, 1, 2]), chunk=r.choice([5, 5, 5, None, 1, 12]),
        steps=r.choice([0, r.randint(0, 40000)]), sit_alerts=r.choice([0, 0, r.randint(1, 14)]),
        pct=r.choice([80, r.randint(0, 100), r.randint(60, 99), 0]), met_limits=r.random() < 0.8,
        sleep=r.choice([(0, 0), (0, 0), tuple(sorted(r.sample(range(0, 1440), 2)))]),
        non_wear_base=r.choice([0, 0, r.randint(0, 200)]))


def run_port(c):
    u = A.User(bmr=c["bmr"], age=c["age"], gender=c["gender"], weight_kg=c["weight_kg"],
               target_mult=c["target_mult"], target_type=c["target_type"])
    a = A.ActInfo(u, user_met_limits=c["met_limits"])
    a.sleep = c["sleep"]
    a.non_wear_base = c["non_wear_base"]
    a.set_target(c["pct"])
    met, n = c["met"], len(c["met"])
    chunk = c["chunk"] or n
    for k in range(0, n, chunk):
        part = met[k:k + chunk]
        a.add_activity(k + len(part) - (1 if chunk == n else 0), c["steps"] if k == 0 else 0, part)
    for _ in range(c["sit_alerts"]):
        a.add_sit_alert()
    return a, a.statistics()


def gen_actinfo(n=28):
    r = random.Random(SEED + 1)
    lines = [
        "// Reference vectors from the Python port tools/actinfo.py on random synthetic days.",
        "// Generated by tools/gen_public_vectors_activity.py; do not edit.",
        "struct Case {", "    runs: &'static [(u8, u16)],", "    chunk: u16,", "    bmr: u32,", "    age: u32,",
        "    gender: u32,", "    weight_kg: u32,", "    target_mult: u32,", "    target_type: u32,",
        "    steps: u32,", "    sit_alerts: u32,", "    pct: u32,", "    met_limits: bool,",
        "    sleep: (i32, i32),", "    non_wear_base: u32,", "    words: [u32; 24],", "    day: Day,",
        "    hourly: [u8; 24],", "}", "", f"const CASES: [Case; {n}] = [",
    ]
    for _ in range(n):
        c = rand_case(r)
        a, s = run_port(c)
        words = [s.eq_distance, s.non_wear, *s.classes, s.avg_met32, s.steps, s.active_cal, s.total_cal,
                 *s.met_min, s.sit_alerts, s.target_distance_m, s.target_miles_x10, s.target_type, s.target_mult,
                 s.target_cal, s.target_steps, s.meters_to_target, s.miles_to_target_x10]
        words = [w & 0xFFFFFFFF for w in words]
        assert len(words) == 24
        d = s.day
        day = (f"Day {{ eq_distance: {d.eq_distance}, eq_target: {d.eq_target}, sedentary_min: {d.sedentary_min}, "
               f"moderate_met_min: {d.moderate_met_min}, vigorous_met_min: {d.vigorous_met_min}, "
               f"sit_alerts: {d.sit_alerts}, age: {d.age}, gender: {d.gender}, moderate_min: {d.moderate_min}, "
               f"vigorous_min: {d.vigorous_min}, target_reached: {d.target_reached} }}")
        lines.append(
            f"    Case {{ runs: &[{rle(c['met'])}], chunk: {c['chunk'] or 0}, bmr: {c['bmr']}, age: {c['age']}, "
            f"gender: {c['gender']}, weight_kg: {c['weight_kg']}, target_mult: {c['target_mult']}, "
            f"target_type: {c['target_type']}, steps: {c['steps']}, sit_alerts: {c['sit_alerts']}, pct: {c['pct']}, "
            f"met_limits: {str(c['met_limits']).lower()}, sleep: ({c['sleep'][0]}, {c['sleep'][1]}), "
            f"non_wear_base: {c['non_wear_base']}, words: {words}, day: {day}, hourly: {list(a.hourly)} }},")
    lines.append("];")
    write("actinfo", "\n".join(lines) + "\n")


def gen_bmr():
    """Ages 0..120, weights 10, 200 and one random value, gender codes 1..3."""
    r = random.Random(SEED + 2)
    rows = []
    for age in range(121):
        for kg in (10, 200, r.randrange(10, 201)):
            for g in (1, 2, 3):
                rows.append((age, kg, g, A.bmr(age, kg, g)))
    body = "\n".join(f"    ({a}, {k}, {g}, {v})," for a, k, g, v in rows)
    write("actinfo_bmr", "// (age, kg, gender code, bmr) from tools/actinfo.py `bmr`.\n"
          "// Generated by tools/gen_public_vectors_activity.py; do not edit.\n"
          f"const BMR_CASES: [(u32, u32, u32, u32); {len(rows)}] = [\n{body}\n];\n")


# ---- actinfo, stateless day path ------------------------------------------------------------------

def rand_met(r, n, zero_first=False):
    """n minutes of MET bytes: rest, sedentary, light and active stretches, gaps and non-wear; each
    value repeats for 1 to 8 minutes."""
    out = []
    while len(out) < n:
        kind = r.choice(["rest", "sed", "sed", "light", "mod", "gap", "nw"])
        length = r.randint(3, 90)
        lo, hi = {"rest": (8, 10), "sed": (11, 15), "light": (16, 35), "mod": (36, 90), "gap": (0, 0), "nw": (1, 1)}[kind]
        while length > 0:
            rep = min(length, r.randint(1, 8))
            out += [r.randint(lo, hi)] * rep
            length -= rep
    out = out[:n]
    if not zero_first and out and out[0] == 0:
        out[0] = r.randint(8, 20)
    return out


def gen_stateless(n=24):
    r = random.Random(SEED + 3)
    lines = [
        "// Reference vectors from the Python port tools/actinfo.py (stateless day path) on random synthetic days.",
        "// Generated by tools/gen_public_vectors_activity.py; do not edit.",
        "struct StatelessCase {", "    cur: &'static [(u8, u16)],", "    prev: &'static [(u8, u16)],",
        "    completed: bool,", "    age: u32,", "    gender: u32,", "    weight_kg: u32,", "    bmr: u32,",
        "    readiness: u32,", "    classes: [u32; 5],", "    hourly: [u8; 24],", "}", "",
        f"const STATELESS_CASES: [StatelessCase; {n}] = [",
    ]
    for _ in range(n):
        age, gender, kg = r.choice([18, 31, 41, 63]), r.choice([1, 2]), r.choice([60, 80])
        bmr = A.bmr(age, kg, gender)
        completed = r.random() < 0.3
        mc = 1440 if completed else r.choice([30, 61, 179, 400, 800, 1439])
        cur, ready = rand_met(r, mc), r.choice([55, 74, 80, 90])
        prev = rand_met(r, 1440, zero_first=r.random() < 0.15)
        user = A.User(bmr=bmr, age=age, gender=gender, weight_kg=kg)
        a = A.ActInfo(user)
        a.stateless = True
        a.set_target(ready)
        a.seed_hourly(prev)
        a.ranges = []
        k = min(mc, 1439)
        a.add_activity(k, 0, cur[:k])
        if completed:
            a.complete_day(cur[1439])
            a.absorb_tail_non_wear()
        st = a.statistics()
        lines.append(f"    StatelessCase {{ cur: &[{rle(cur)}], prev: &[{rle(prev)}], completed: {str(completed).lower()}, "
                     f"age: {age}, gender: {gender}, weight_kg: {kg}, bmr: {bmr}, readiness: {ready}, "
                     f"classes: {list(st.classes)}, hourly: {list(a.hourly)} }},")
    lines.append("];")
    write("actinfo_stateless", "\n".join(lines) + "\n")


# ---- activity score ------------------------------------------------------------------------------

def rand_score_day(r, today):
    d = AS.Day(
        eq_distance=r.choice([0, 400, 1011, 3000, 4000, 4001, 9000, 20000]),
        eq_target=r.choice([0, 2000, 6000, 12000]), sedentary_min=r.choice([0, 200, 350, 600, 950, 1000, 1030]),
        moderate_met_min=r.choice([0, 0, 20, 100, 400, 1500]), vigorous_met_min=r.choice([0, 0, 20, 80, 300, 900]),
        moderate_min=r.choice([0, 20, 90]), vigorous_min=r.choice([0, 0, 10, 15, 16, 45, 46, 80]),
        target_reached=r.choice([0, 0, 0, 1, 2]))
    if today:
        d.sit_alerts = r.randint(0, 12)
        d.age = r.choice([18, 25, 33, 47, 62, 80])
        d.gender = r.choice([1, 2, 3])
    return d


def rust_day(d):
    return (f"Day {{ eq_distance: {d.eq_distance}, eq_target: {d.eq_target}, sedentary_min: {d.sedentary_min}, "
            f"moderate_met_min: {d.moderate_met_min}, vigorous_met_min: {d.vigorous_met_min}, sit_alerts: {d.sit_alerts}, "
            f"age: {d.age}, gender: {d.gender}, moderate_min: {d.moderate_min}, vigorous_min: {d.vigorous_min}, "
            f"target_reached: {d.target_reached} }}")


def gen_score(n=48):
    r = random.Random(SEED + 4)
    lines = ["// Reference vectors from the Python port tools/activity_score.py on random synthetic day records.",
             "// Generated by tools/gen_public_vectors_activity.py; do not edit.",
             f"const VECTORS: [(&[Day], u32, [f32; 7], u32); {n}] = ["]
    for _ in range(n):
        k = r.randint(1, 10)
        days = [rand_score_day(r, False) for _ in range(k - 1)] + [rand_score_day(r, True)]
        for d in days[:-1]:
            if r.random() < 0.2:
                d.__dict__.update(AS.Day().__dict__)
        j = r.choice([0, 3, 9, 10, 11, 60, 400])
        c = AS.contributors(days, j)
        total = int(sum(w * v for w, v in zip(AS.WEIGHTS, c)) + 0.5)  # hundredths of a point
        lines.append(f"    (&[{', '.join(rust_day(d) for d in days)}], {j}, [{', '.join(f'{v:.5f}' for v in c)}], {total}),")
    lines.append("];")
    write("activity_score", "\n".join(lines) + "\n")


